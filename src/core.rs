#[derive(Debug, Error)]
pub enum AgentError {
    #[error("agent is closed")]
    Closed,
    #[error("no active turn")]
    NoActiveTurn,
    #[error("an active turn is already running")]
    NotIdle,
    #[error("invalid turn: {0}")]
    InvalidTurn(String),
    #[error("backend: {0}")]
    Backend(#[from] BackendError),
    #[error("session: {0}")]
    Session(#[from] SessionError),
    #[error("b3 handoff: {0}")]
    B3(#[from] B3Error),
    #[error("tool: {0}")]
    Tool(#[from] ToolError),
    #[error("tool loop exceeded {0} iterations")]
    ToolLoopLimit(usize),
    #[error("operation recovery: {0}")]
    Recovery(String),
    #[error("resource governance: {0}")]
    Governance(String),
    #[error("approval: {0}")]
    Approval(#[from] ApprovalError),
}

impl AgentError {
    /// Stable machine-readable classification for headless hosts.
    pub const fn code(&self) -> &'static str {
        match self {
            Self::Closed => "agent_closed",
            Self::NoActiveTurn => "no_active_turn",
            Self::NotIdle => "agent_not_idle",
            Self::InvalidTurn(_) => "invalid_turn",
            Self::Backend(error) => error.code(),
            Self::Session(_) => "session_error",
            Self::B3(_) => "handoff_error",
            Self::Tool(_) => "tool_error",
            Self::ToolLoopLimit(_) => "tool_loop_limit",
            Self::Recovery(_) => "operation_recovery",
            Self::Governance(_) => "resource_budget_exceeded",
            Self::Approval(_) => "approval_error",
        }
    }
}

