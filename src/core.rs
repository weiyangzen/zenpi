/// One event from the login flow, handed to the terminal host.
enum CliLoginEvent {
    Browser {
        flow_id: crate::auth::LoginFlowId,
        prompt_id: u64,
        url: String,
        manual: crate::auth::callback::ManualSubmission,
    },
    Device {
        flow_id: crate::auth::LoginFlowId,
        prompt_id: u64,
        uri: &'static str,
        code: String,
    },
    Notice(crate::auth::LoginState),
    Dismissed,
    Pasted(String),
    Finished(Box<crate::auth::LoginOutcome>),
}

/// Open a URL in the platform browser.  Best effort: a missing opener never
/// fails a login, because the URL is printed either way.
fn open_browser(url: &str) {
    #[cfg(target_os = "macos")]
    let opener = "open";
    #[cfg(all(unix, not(target_os = "macos")))]
    let opener = "xdg-open";
    #[cfg(windows)]
    let opener = "explorer";
    let _ = std::process::Command::new(opener)
        .arg(url)
        .stdin(std::process::Stdio::null())
        .stdout(std::process::Stdio::null())
        .stderr(std::process::Stdio::null())
        .spawn();
}

/// Forward pasted redirect URIs to the login flow.  The thread ends at EOF, so
/// a non-interactive stdin simply never supplies a manual code.
fn spawn_stdin_reader(sender: std::sync::mpsc::Sender<CliLoginEvent>) {
    std::thread::spawn(move || {
        let mut reader = std::io::BufReader::new(std::io::stdin());
        let mut line = String::new();
        loop {
            line.clear();
            match reader.read_line(&mut line) {
                Ok(0) | Err(_) => return,
                Ok(_) => {
                    if sender.send(CliLoginEvent::Pasted(line.clone())).is_err() {
                        return;
                    }
                }
            }
        }
    });
}

/// Drive one interactive Codex login from the terminal.
///
/// The authorization URL and any device code are written to stderr only; they
/// never reach a journal, a log, or a status response.  The flow runs on a
/// worker thread so the loopback callback keeps being pumped while this thread
/// waits for a pasted redirect URI.
///
/// Cancellation is the process's own SIGINT — exiting closes the callback
/// listener — and `LoginControl` bounds the whole flow to 15 minutes.
pub(crate) fn run_cli_codex_login(
    paths: &crate::config::ConfigPaths,
    device: bool,
    no_browser: bool,
    alias: Option<&str>,
    model: Option<&str>,
) -> Result<(), ZenpiError> {
    let store = crate::config::credential_store(paths, true)?;
    let credential_id = crate::auth::store::CredentialStore::new_credential_id()
        .map_err(|error| ZenpiError::Message(error.to_string()))?;
    let (sender, receiver) = std::sync::mpsc::channel::<CliLoginEvent>();

    let worker_sender = sender.clone();
    let worker_id = credential_id.clone();
    let worker = std::thread::spawn(move || {
        let credential_id = worker_id;
        let cancelled = || false;
        let mut admission = |_kind: crate::auth::AuthHttpKind| Ok(());
        let mut interaction = |event: crate::auth::AuthInteraction| {
            let converted = match event {
                crate::auth::AuthInteraction::Notify { state, .. } => CliLoginEvent::Notice(state),
                crate::auth::AuthInteraction::Prompt {
                    flow_id,
                    prompt_id,
                    prompt,
                } => match prompt {
                    crate::auth::AuthPrompt::Browser {
                        authorization_url,
                        manual,
                    } => CliLoginEvent::Browser {
                        flow_id,
                        prompt_id,
                        url: authorization_url,
                        manual,
                    },
                    crate::auth::AuthPrompt::Device {
                        verification_uri,
                        user_code,
                    } => CliLoginEvent::Device {
                        flow_id,
                        prompt_id,
                        uri: verification_uri,
                        code: user_code,
                    },
                },
                crate::auth::AuthInteraction::CancelPrompt { .. } => CliLoginEvent::Dismissed,
            };
            // A closed receiver means the host gave up: fail the interaction
            // rather than blocking the flow forever.
            worker_sender
                .send(converted)
                .map_err(|_| crate::auth::AuthError::InteractionFailed)
        };
        let mut control = crate::auth::LoginControl::new(
            &cancelled,
            Instant::now() + Duration::from_secs(15 * 60),
            MAX_CLI_LOGIN_SENDS,
            &mut admission,
            &mut interaction,
        );
        let request = crate::auth::LoginRequest {
            store: &store,
            credential_id: &credential_id,
            expected_revision: None,
        };
        let outcome = if device {
            crate::auth::codex::begin_device_login()
                .and_then(|flow| crate::auth::codex::login_device(flow, request, &mut control))
        } else {
            crate::auth::codex::begin_browser_login()
                .and_then(|flow| crate::auth::codex::login_browser(flow, request, &mut control))
        };
        let _ = worker_sender.send(CliLoginEvent::Finished(Box::new(outcome)));
    });

    let stdin = (!device).then(|| spawn_stdin_reader(sender.clone()));
    // The manual code is only meaningful for the prompt that is currently open.
    let mut pending = None;
    let outcome = loop {
        let Ok(event) = receiver.recv() else {
            break Err(crate::auth::AuthError::LoginFailed);
        };
        match event {
            CliLoginEvent::Browser {
                flow_id,
                prompt_id,
                url,
                manual,
            } => {
                eprintln!("authorize this login to continue:\n  {url}");
                if !no_browser {
                    open_browser(&url);
                }
                eprintln!(
                    "if the browser did not complete it, paste the redirect URL here and press enter"
                );
                pending = Some((flow_id, prompt_id, manual));
            }
            CliLoginEvent::Device { uri, code, .. } => {
                eprintln!("open {uri} and enter code: {code}");
            }
            CliLoginEvent::Notice(state) => eprintln!("{}", login_state_label(state)),
            CliLoginEvent::Dismissed => pending = None,
            CliLoginEvent::Pasted(line) => {
                if let Some((flow_id, prompt_id, manual)) = &pending {
                    match manual.submit(flow_id, *prompt_id, line.trim()) {
                        Ok(()) => pending = None,
                        // A late paste after the browser won is not an error the
                        // user needs to see; anything else is worth reporting.
                        Err(crate::auth::AuthError::StalePrompt) => {}
                        Err(error) => eprintln!("the pasted code was rejected: {error}"),
                    }
                }
            }
            CliLoginEvent::Finished(result) => break *result,
        }
    };
    let _ = stdin;
    let _ = worker.join();

    outcome.map_err(|error| ZenpiError::Message(format!("login failed: {error}")))?;

    let alias = alias.unwrap_or("codex");
    let binding = crate::config::bind_credential_profile(
        paths,
        alias,
        "openai-codex",
        model,
        None,
        "oauth",
        &credential_id,
        None,
        None,
    );
    if let Err(error) = binding {
        return Err(ZenpiError::Message(format!(
            "credential {credential_id} was stored but profile `{alias}` was not bound: {error}"
        )));
    }
    eprintln!("stored {credential_id}; profile `{alias}` bound");
    Ok(())
}

/// HTTP sends one CLI login may make.  The browser flow needs a single code
/// exchange; the device flow polls, so it needs a bounded budget rather than a
/// single attempt.
const MAX_CLI_LOGIN_SENDS: u32 = 256;

/// Resolve the third selector token of `config auth …` / `config add auth …`.
/// Returns `None` for the two-level commands, leaving their arguments alone.
fn nested_command(
    group: &str,
    action: &str,
    args: &mut std::iter::Peekable<impl Iterator<Item = String>>,
) -> Result<Option<CliCommand>, ZenpiError> {
    match (group, action) {
        ("config", "auth") => {
            let selector = args
                .next()
                .ok_or_else(|| ZenpiError::arguments("config auth requires an action"))?;
            match selector.as_str() {
                "list" => Ok(Some(CliCommand::ConfigAuthList)),
                _ => Err(ZenpiError::arguments(format!(
                    "unknown config auth action `{selector}`"
                ))),
            }
        }
        ("config", "add") => {
            let target = args
                .next()
                .ok_or_else(|| ZenpiError::arguments("config add requires a target"))?;
            if target != "auth" {
                return Err(ZenpiError::arguments(format!(
                    "unknown config add target `{target}`"
                )));
            }
            let method = args
                .next()
                .ok_or_else(|| ZenpiError::arguments("config add auth requires codex or apikey"))?;
            match method.as_str() {
                "codex" => Ok(Some(CliCommand::ConfigAddAuthCodex)),
                "apikey" => Ok(Some(CliCommand::ConfigAddAuthApikey)),
                _ => Err(ZenpiError::arguments(format!(
                    "unknown config add auth method `{method}`"
                ))),
            }
        }
        _ => Ok(None),
    }
}

fn is_auth_add(command: Option<CliCommand>) -> bool {
    matches!(
        command,
        Some(CliCommand::ConfigAddAuthCodex | CliCommand::ConfigAddAuthApikey)
    )
}

fn lookup_command(group: &str, action: &str) -> Result<CliCommand, ZenpiError> {
    Ok(match (group, action) {
        ("config", "import-codex") => CliCommand::ConfigImportCodex,
        ("config", "doctor") => CliCommand::ConfigDoctor,
        ("config", "list") => CliCommand::ConfigList,
        ("config", "use") => CliCommand::ConfigUse,
        ("pair", "import-codex") => CliCommand::PairImportCodex,
        ("pair", "status") => CliCommand::PairStatus,
        ("pair", "revoke") => CliCommand::PairRevoke,
        ("session", "list") => CliCommand::SessionList,
        ("session", "inspect") => CliCommand::SessionInspect,
        ("session", "fork") => CliCommand::SessionFork,
        ("session", "export") => CliCommand::SessionExport,
        ("session", "import") => CliCommand::SessionImport,
        ("session", "gc") => CliCommand::SessionGc,
        ("extension", "list") => CliCommand::ExtensionList,
        ("extension", "install") => CliCommand::ExtensionInstall,
        ("extension", "remove") => CliCommand::ExtensionRemove,
        ("extension", "disable") => CliCommand::ExtensionDisable,
        ("extension", "enable") => CliCommand::ExtensionEnable,
        ("extension", "upgrade") => CliCommand::ExtensionUpgrade,
        _ => {
            return Err(ZenpiError::arguments(format!(
                "unknown {group} action `{action}`"
            )));
        }
    })
}

pub fn parse_args<I, S>(args: I) -> Result<CliOptions, ZenpiError>
where
    I: IntoIterator<Item = S>,
    S: Into<String>,
{
    let mut options = CliOptions::default();
    let mut args = args.into_iter().map(Into::into).peekable();
    if args.peek().is_some_and(|argument| {
        matches!(
            argument.as_str(),
            "config" | "pair" | "session" | "extension"
        )
    }) {
        let group = args.next().unwrap_or_default();
        let action = args
            .next()
            .ok_or_else(|| ZenpiError::arguments(format!("{group} requires an action")))?;
        // `config auth …` and `config add auth …` carry a third selector token
        // before the flags.
        if let Some(command) = nested_command(&group, &action, &mut args)? {
            options.command = Some(command);
        } else {
            options.command = Some(lookup_command(&group, &action)?);
        }
        while let Some(argument) = args.next() {
            match argument.as_str() {
                "--json"
                    if matches!(
                        options.command,
                        Some(
                            CliCommand::ConfigDoctor
                                | CliCommand::ConfigList
                                | CliCommand::ConfigAuthList
                                | CliCommand::ConfigAddAuthApikey
                                | CliCommand::PairStatus
                                | CliCommand::SessionList
                                | CliCommand::SessionInspect
                                | CliCommand::ExtensionList
                        )
                    ) =>
                {
                    options.json = true;
                }
                "--alias" if is_auth_add(options.command) => {
                    options.alias = Some(
                        args.next()
                            .ok_or_else(|| ZenpiError::arguments("--alias requires a name"))?,
                    );
                }
                "--stdin" if options.command == Some(CliCommand::ConfigAddAuthApikey) => {
                    options.stdin = true;
                }
                "--wire" if is_auth_add(options.command) => {
                    options.wire_api = Some(
                        args.next()
                            .ok_or_else(|| ZenpiError::arguments("--wire requires a protocol"))?,
                    );
                }
                "--header" if is_auth_add(options.command) => {
                    options.auth_header = Some(
                        args.next()
                            .ok_or_else(|| ZenpiError::arguments("--header requires a policy"))?,
                    );
                }
                "--device" if options.command == Some(CliCommand::ConfigAddAuthCodex) => {
                    options.device = true;
                }
                "--no-browser" if options.command == Some(CliCommand::ConfigAddAuthCodex) => {
                    options.no_browser = true;
                }
                // Positional values for the auth commands must not swallow an
                // unrecognized flag: a stray `--json` would silently become a
                // login's optional email and start a real flow.
                value
                    if is_auth_add(options.command)
                        && !value.starts_with('-')
                        && options.command_value.is_none() =>
                {
                    options.command_value = Some(value.to_owned());
                }
                value
                    if options.command == Some(CliCommand::ConfigAddAuthApikey)
                        && !value.starts_with('-')
                        && options.command_value2.is_none() =>
                {
                    options.command_value2 = Some(value.to_owned());
                }
                "--yes"
                    if matches!(
                        options.command,
                        Some(CliCommand::PairRevoke | CliCommand::SessionGc)
                    ) =>
                {
                    options.yes = true;
                }
                "--json" if options.command == Some(CliCommand::PairRevoke) => {
                    options.json = true;
                }
                // The auth management commands take their profile from
                // --alias and their own positional arguments; --profile would
                // silently overwrite one of them.
                "--profile"
                    if !is_auth_add(options.command)
                        && options.command != Some(CliCommand::ConfigAuthList) =>
                {
                    options.command_value = Some(
                        args.next()
                            .ok_or_else(|| ZenpiError::arguments("--profile requires a name"))?,
                    );
                }
                "--model" if is_auth_add(options.command) => {
                    options.model = Some(
                        args.next()
                            .ok_or_else(|| ZenpiError::arguments("--model requires a name"))?,
                    );
                }
                value
                    if matches!(options.command, Some(CliCommand::ConfigUse))
                        && options.command_value.is_none() =>
                {
                    options.command_value = Some(value.to_owned());
                }
                "--retain-newest" if matches!(options.command, Some(CliCommand::SessionGc)) => {
                    let value = args.next().ok_or_else(|| {
                        ZenpiError::arguments("--retain-newest requires a number")
                    })?;
                    let parsed = value.parse::<usize>().map_err(|_| {
                        ZenpiError::arguments("--retain-newest must be a non-negative integer")
                    })?;
                    if parsed > crate::slash::MAX_SESSION_GC_RETAIN_NEWEST {
                        return Err(ZenpiError::arguments(format!(
                            "--retain-newest must be at most {}",
                            crate::slash::MAX_SESSION_GC_RETAIN_NEWEST
                        )));
                    }
                    options.retain_newest = Some(parsed);
                }
                "--older-than-seconds"
                    if matches!(options.command, Some(CliCommand::SessionGc)) =>
                {
                    let value = args.next().ok_or_else(|| {
                        ZenpiError::arguments("--older-than-seconds requires a number")
                    })?;
                    let parsed = value.parse::<u64>().map_err(|_| {
                        ZenpiError::arguments("--older-than-seconds must be a non-negative integer")
                    })?;
                    if parsed > crate::slash::MAX_SESSION_GC_AGE_SECONDS {
                        return Err(ZenpiError::arguments(format!(
                            "--older-than-seconds must be at most {}",
                            crate::slash::MAX_SESSION_GC_AGE_SECONDS
                        )));
                    }
                    options.older_than_seconds = Some(parsed);
                }
                value
                    if matches!(
                        options.command,
                        Some(
                            CliCommand::SessionInspect
                                | CliCommand::SessionFork
                                | CliCommand::SessionExport
                                | CliCommand::SessionImport
                        )
                    ) && options.command_value.is_none() =>
                {
                    options.command_value = Some(value.to_owned());
                }
                value
                    if matches!(
                        options.command,
                        Some(
                            CliCommand::ExtensionInstall
                                | CliCommand::ExtensionRemove
                                | CliCommand::ExtensionDisable
                                | CliCommand::ExtensionEnable
                                | CliCommand::ExtensionUpgrade
                        )
                    ) && options.command_value.is_none() =>
                {
                    options.command_value = Some(value.to_owned());
                }
                value
                    if matches!(
                        options.command,
                        Some(
                            CliCommand::SessionFork
                                | CliCommand::SessionExport
                                | CliCommand::SessionImport
                        )
                    ) && options.command_value2.is_none() =>
                {
                    options.command_value2 = Some(value.to_owned());
                }
                _ => {
                    return Err(ZenpiError::arguments(format!(
                        "unsupported argument for {group} {action}: `{argument}`"
                    )));
                }
            }
        }
        if matches!(options.command, Some(CliCommand::ConfigUse)) && options.command_value.is_none()
        {
            return Err(ZenpiError::arguments("config use requires a profile name"));
        }
        if matches!(options.command, Some(CliCommand::PairRevoke)) && !options.yes {
            return Err(ZenpiError::arguments(
                "pair revoke requires --yes confirmation",
            ));
        }
        if matches!(options.command, Some(CliCommand::SessionInspect))
            && options.command_value.is_none()
        {
            return Err(ZenpiError::arguments("session inspect requires PATH"));
        }
        if options.command == Some(CliCommand::ConfigAddAuthApikey) {
            if options.command_value.is_none() || options.command_value2.is_none() {
                return Err(ZenpiError::arguments(
                    "config add auth apikey requires BASE_URL and PROVIDER",
                ));
            }
            if !options.stdin {
                return Err(ZenpiError::arguments(
                    "config add auth apikey requires --stdin; keys are never taken from the argument list",
                ));
            }
        }
        if options.command == Some(CliCommand::ConfigAddAuthCodex)
            && options.device
            && options.no_browser
        {
            return Err(ZenpiError::arguments(
                "--device and --no-browser select different login flows",
            ));
        }
        if matches!(
            options.command,
            Some(
                CliCommand::ExtensionInstall
                    | CliCommand::ExtensionRemove
                    | CliCommand::ExtensionDisable
                    | CliCommand::ExtensionEnable
                    | CliCommand::ExtensionUpgrade
            )
        ) && options.command_value.is_none()
        {
            return Err(ZenpiError::arguments(format!(
                "extension {action} requires a source path or extension name"
            )));
        }
        if matches!(
            options.command,
            Some(CliCommand::SessionFork | CliCommand::SessionExport | CliCommand::SessionImport)
        ) && (options.command_value.is_none() || options.command_value2.is_none())
        {
            return Err(ZenpiError::arguments(format!(
                "session {action} requires SOURCE and DESTINATION"
            )));
        }
        if matches!(options.command, Some(CliCommand::SessionGc))
            && (!options.yes
                || options.retain_newest.is_none()
                || options.older_than_seconds.is_none())
        {
            return Err(ZenpiError::arguments(
                "session gc requires --retain-newest N --older-than-seconds N --yes",
            ));
        }
        return Ok(options);
    }
    while let Some(argument) = args.next() {
        let (flag, inline) = argument
            .split_once('=')
            .map_or((argument.as_str(), None), |(flag, value)| {
                (flag, Some(value))
            });
        match flag {
            "--help" | "-h" => options.help = true,
            "--headless" => {
                if inline.is_some() {
                    return Err(ZenpiError::arguments("--headless does not take a value"));
                }
                options.mode = RunMode::Headless;
            }
            "--tui" => {
                if inline.is_some() {
                    return Err(ZenpiError::arguments("--tui does not take a value"));
                }
                options.mode = RunMode::Tui;
            }
            "--mode" => {
                let value = inline
                    .map(str::to_owned)
                    .or_else(|| args.next())
                    .ok_or_else(|| ZenpiError::arguments("--mode requires tui or headless"))?;
                options.mode = match value.as_str() {
                    "tui" => RunMode::Tui,
                    "headless" => RunMode::Headless,
                    _ => return Err(ZenpiError::arguments("--mode must be tui or headless")),
                };
            }
            "--session" => {
                let value = inline
                    .map(str::to_owned)
                    .or_else(|| args.next())
                    .ok_or_else(|| ZenpiError::arguments("--session requires a path"))?;
                if value.trim().is_empty() {
                    return Err(ZenpiError::arguments("--session path is empty"));
                }
                options.session = PathBuf::from(value);
            }
            "--max-tool-iterations" => {
                let value = inline
                    .map(str::to_owned)
                    .or_else(|| args.next())
                    .ok_or_else(|| {
                        ZenpiError::arguments("--max-tool-iterations requires a number")
                    })?;
                let iterations = value.trim().parse::<usize>().map_err(|_| {
                    ZenpiError::arguments("--max-tool-iterations must be an integer")
                })?;
                if !(1..=10_000).contains(&iterations) {
                    return Err(ZenpiError::arguments(
                        "--max-tool-iterations must be between 1 and 10000",
                    ));
                }
                options.max_tool_iterations = iterations;
            }
            "--auto" => {
                if inline.is_some() {
                    return Err(ZenpiError::arguments("--auto does not take a value"));
                }
                options.auto = true;
            }
            "-s" => {
                let value = inline
                    .map(str::to_owned)
                    .or_else(|| args.next())
                    .ok_or_else(|| ZenpiError::arguments("-s requires a session name or id"))?;
                let value = value.trim();
                if value.is_empty() {
                    return Err(ZenpiError::arguments("-s session reference is empty"));
                }
                options.session_ref = Some(value.to_owned());
            }
            "--backend" => {
                options.backend = inline
                    .map(str::to_owned)
                    .or_else(|| args.next())
                    .ok_or_else(|| ZenpiError::arguments("--backend requires echo or openai"))?;
                options.backend_explicit = true;
                if options.backend.trim().is_empty()
                    || options.backend.chars().any(char::is_control)
                {
                    return Err(ZenpiError::arguments("--backend name is invalid"));
                }
            }
            "--model" => {
                let model = inline
                    .map(str::to_owned)
                    .or_else(|| args.next())
                    .ok_or_else(|| ZenpiError::arguments("--model requires a name"))?;
                if model.trim().is_empty()
                    || model.len() > 256
                    || model.chars().any(char::is_control)
                {
                    return Err(ZenpiError::arguments(
                        "--model must be non-empty and at most 256 bytes",
                    ));
                }
                options.model = Some(model);
            }
            "--profile" => {
                let profile = inline
                    .map(str::to_owned)
                    .or_else(|| args.next())
                    .ok_or_else(|| ZenpiError::arguments("--profile requires a name"))?;
                if profile.trim().is_empty()
                    || profile.len() > 128
                    || !profile.chars().all(|character| {
                        character.is_ascii_alphanumeric() || "_-".contains(character)
                    })
                {
                    return Err(ZenpiError::arguments(
                        "--profile must use only letters, digits, `_`, or `-` and be at most 128 bytes",
                    ));
                }
                options.profile = Some(profile);
            }
            other if other.starts_with('-') => {
                return Err(ZenpiError::arguments(format!("unknown option `{other}`")));
            }
            other => {
                return Err(ZenpiError::arguments(format!(
                    "unexpected argument `{other}`"
                )));
            }
        }
    }
    Ok(options)
}

fn make_backend(options: &CliOptions) -> Result<Box<dyn Backend>, ZenpiError> {
    match options.backend.as_str() {
        "echo" if options.backend_explicit && cfg!(feature = "dev-fixtures") => {
            Ok(Box::new(EchoBackend))
        }
        "echo" => Err(ZenpiError::arguments(
            "echo is a test fixture; rebuild with --features dev-fixtures and pass --backend echo",
        )),
        "openai" | "anthropic" | "google" => {
            let effective = crate::config::resolve_workspace(
                &crate::config::ConfigOverrides {
                    profile: options.profile.clone(),
                    backend: options.backend_explicit.then(|| options.backend.clone()),
                    model: options.model.clone(),
                    ..crate::config::ConfigOverrides::default()
                },
                Some(&env::current_dir()?),
            )?;
            backend_from_effective(effective)
        }
        other => Err(ZenpiError::arguments(format!(
            "unknown backend `{other}` (expected echo, openai, anthropic or google)"
        ))),
    }
}

/// Build a backend for a named profile without disturbing the running one.
///
/// A candidate is constructed and validated before the owner is asked to swap,
/// so a profile that cannot be resolved, or whose credential is missing, leaves
/// the running connection exactly as it was.
pub(crate) fn connection_candidate(
    profile: &str,
    model: Option<&str>,
) -> Result<Box<dyn Backend>, ZenpiError> {
    let effective = crate::config::resolve_default(&crate::config::ConfigOverrides {
        profile: Some(profile.to_owned()),
        model: model.map(str::to_owned),
        ..crate::config::ConfigOverrides::default()
    })?;
    backend_from_effective(effective)
}

fn backend_from_effective(
    effective: crate::config::EffectiveConfig,
) -> Result<Box<dyn Backend>, ZenpiError> {
    if let Some(connection) = effective.provider_connection(1)? {
        let paths = crate::config::ConfigPaths::discover()?;
        // The store opens every path component with O_NOFOLLOW, so an ancestor
        // that is a link (macOS `/var` and `/tmp`) has to be resolved first;
        // without that, an explicit connection cannot start under any temp
        // home.  `credential_store` is the same helper the config commands use.
        let store = crate::config::credential_store(&paths, false)?;
        let registry =
            crate::providers::registry::ModelRegistry::with_overrides(&effective.model_overrides)
                .map_err(|error| ZenpiError::Message(error.to_string()))?;
        let model = effective
            .model
            .ok_or_else(|| ZenpiError::arguments("explicit connection requires a model"))?;
        let backend = OpenAiCompatibleBackend::from_connection(
            connection,
            store,
            registry,
            model,
            effective.model_reasoning_effort,
            effective.model_verbosity,
            std::time::Duration::from_secs(effective.timeout_seconds.unwrap_or(120)),
        )?
        .with_max_retries(effective.max_retries.unwrap_or(2))?;
        return Ok(Box::new(backend));
    }
    if !matches!(
        effective.backend.as_str(),
        "openai" | "anthropic" | "google"
    ) {
        return Err(ZenpiError::arguments(
            "unsupported production provider backend",
        ));
    }
    let base_url = effective.base_url.ok_or_else(|| {
        ZenpiError::arguments(
            "no provider URL configured; run `zenpi config import-codex` or set ZENPI_BASE_URL",
        )
    })?;
    let api_key = if effective.requires_openai_auth {
        Some(effective.api_key.ok_or_else(|| {
                    ZenpiError::arguments(
                        "no provider API key configured; run `zenpi config import-codex` or set ZENPI_API_KEY",
                    )
                })?)
    } else {
        effective.api_key
    };
    let model = effective.model.ok_or_else(|| {
        ZenpiError::arguments(
            "no provider model configured; run `zenpi config import-codex` or set ZENPI_MODEL",
        )
    })?;
    let wire_api = effective
        .wire_api
        .as_deref()
        .unwrap_or(if effective.backend == "google" {
            "google_generative_ai"
        } else if effective.backend == "anthropic" {
            "anthropic_messages"
        } else {
            "responses"
        })
        .parse::<OpenAiWireApi>()?;
    let registry =
        crate::providers::registry::ModelRegistry::with_overrides(&effective.model_overrides)
            .map_err(|error| ZenpiError::Message(error.to_string()))?;
    if effective.backend == "anthropic" && wire_api != OpenAiWireApi::AnthropicMessages {
        return Err(ZenpiError::arguments(
            "anthropic backend requires anthropic_messages wire",
        ));
    }
    if effective.backend == "google" && wire_api != OpenAiWireApi::GoogleGenerativeAi {
        return Err(ZenpiError::arguments(
            "google backend requires google_generative_ai wire",
        ));
    }
    let provider = effective.provider.unwrap_or_else(|| {
        if wire_api == OpenAiWireApi::GoogleGenerativeAi {
            return "google".into();
        }
        if wire_api == OpenAiWireApi::AnthropicMessages {
            "anthropic".into()
        } else {
            "openai".into()
        }
    });
    // Fault tolerance: a configured reasoning effort that the selected
    // model/wire does not advertise must not brick startup. Drop it (a stale
    // copied config or an uncatalogued model is common) and keep the model;
    // explicit runtime `/reasoning` stays strict.
    let mut reasoning_effort = effective.model_reasoning_effort;
    if let Some(effort) = reasoning_effort.clone()
        && let Ok(descriptor) = registry.resolve(&provider, &model)
        && descriptor
            .validate_reasoning(
                crate::backend::ProviderCapabilities::for_wire_api(wire_api),
                Some(effort.as_str()),
            )
            .is_err()
    {
        eprintln!(
            "zenpi: ignoring configured reasoning effort `{effort}`: not supported by {provider}/{model}"
        );
        reasoning_effort = None;
    }
    let backend = OpenAiCompatibleBackend::from_values_with_settings_and_timeout(
        base_url,
        api_key,
        model,
        wire_api,
        reasoning_effort,
        effective.model_verbosity,
        std::time::Duration::from_secs(effective.timeout_seconds.unwrap_or(120)),
    )?
    .with_max_retries(effective.max_retries.unwrap_or(2))?
    .with_model_registry(provider, registry)?;
    Ok(Box::new(backend))
}

fn print_help() {
    println!(
        "zenpi [--mode tui|headless] [--session PATH | -s NAME|ID] [--auto] [--max-tool-iterations N] [--backend openai|anthropic|google] [--profile NAME] [--model NAME]"
    );
    println!("zenpi config import-codex [--profile NAME]");
    println!("zenpi config doctor [--profile NAME] [--json]");
    println!("zenpi config list [--json] | config use NAME");
    println!("zenpi config auth list [--json]");
    println!(
        "zenpi config add auth apikey BASE_URL PROVIDER --stdin [--wire W] [--header H] [--alias NAME] [--model NAME]"
    );
    println!(
        "zenpi config add auth codex [EMAIL] [--alias NAME] [--model NAME] [--device | --no-browser]"
    );
    println!("zenpi pair import-codex|status|revoke --yes [--profile NAME]");
    println!("zenpi session list [--json] | inspect PATH [--json]");
    println!("zenpi session fork|export|import SOURCE DESTINATION");
    println!("zenpi session gc --retain-newest N --older-than-seconds N --yes");
    println!("zenpi extension list [--json] | install|upgrade PATH");
    println!("zenpi extension disable|enable|remove NAME");
    println!(
        "default provider: ~/.zenpi (or read-only ~/.codex fallback); echo exists only in dev-fixtures builds"
    );
}

/// Binary entry point shared with tests and embedders.
pub fn run() -> Result<(), ZenpiError> {
    let options = parse_args(env::args().skip(1))?;
    if options.help {
        print_help();
        return Ok(());
    }
    if let Some(command) = options.command {
        return match command {
            CliCommand::ConfigImportCodex | CliCommand::PairImportCodex => {
                let summary = match options.command_value.as_deref() {
                    Some(profile) => crate::config::import_codex_profile(profile)?,
                    None => crate::config::import_codex()?,
                };
                println!("{}", summary.display());
                Ok(())
            }
            CliCommand::ConfigAuthList => {
                let paths = crate::config::ConfigPaths::discover()?;
                let entries = crate::config::auth_list(&paths)?;
                if options.json {
                    println!(
                        "{}",
                        serde_json::to_string(&entries)
                            .map_err(|error| ZenpiError::Message(error.to_string()))?
                    );
                } else if entries.is_empty() {
                    println!("no stored credentials");
                } else {
                    for entry in &entries {
                        println!(
                            "{} provider={} kind={} state={} revision={} expires_at={} profiles={}",
                            entry.credential_id,
                            entry.provider,
                            entry.kind,
                            entry.state,
                            entry.revision,
                            display_option(
                                entry
                                    .expires_at_ms
                                    .map(|value| value.to_string())
                                    .as_deref()
                            ),
                            if entry.profiles.is_empty() {
                                "-".to_owned()
                            } else {
                                entry.profiles.join(",")
                            }
                        );
                    }
                }
                Ok(())
            }
            CliCommand::ConfigAddAuthApikey => {
                let base_url = options.command_value.clone().unwrap_or_default();
                let provider = options.command_value2.clone().unwrap_or_default();
                // Read the key before touching anything on disk: a cancelled or
                // empty read must not leave a credential behind.
                let key = read_api_key_from_stdin()?;
                let paths = crate::config::ConfigPaths::discover()?;
                let report = crate::config::add_auth_apikey(
                    &paths,
                    &base_url,
                    &provider,
                    key,
                    crate::config::ApiKeyProfile {
                        alias: options.alias.as_deref(),
                        model: options.model.as_deref(),
                        wire: options.wire_api.as_deref(),
                        auth_header: options.auth_header.as_deref(),
                    },
                )?;
                print_auth_add_report(&report, options.json)?;
                if let Some(error) = &report.binding_error {
                    return Err(ZenpiError::Message(format!(
                        "credential {} was stored but profile `{}` was not bound: {error}",
                        report.credential_id, report.alias
                    )));
                }
                Ok(())
            }
            CliCommand::ConfigAddAuthCodex => {
                let paths = crate::config::ConfigPaths::discover()?;
                run_cli_codex_login(
                    &paths,
                    options.device,
                    options.no_browser,
                    options.alias.as_deref(),
                    options.model.as_deref(),
                )?;
                Ok(())
            }
            CliCommand::ConfigDoctor | CliCommand::PairStatus => {
                let paths = crate::config::ConfigPaths::discover()?;
                let report =
                    crate::config::status_for_profile(&paths, options.command_value.as_deref())?;
                if options.json {
                    println!(
                        "{}",
                        serde_json::to_string(&report)
                            .map_err(|error| ZenpiError::Message(error.to_string()))?
                    );
                } else {
                    print_config_status(&report);
                }
                if report.is_ready() {
                    Ok(())
                } else {
                    Err(ZenpiError::arguments(
                        "provider configuration is not ready; run `zenpi config import-codex` or set ZENPI_BASE_URL, ZENPI_API_KEY, and ZENPI_MODEL",
                    ))
                }
            }
            CliCommand::ConfigList => {
                let paths = crate::config::ConfigPaths::discover()?;
                let profiles = crate::config::list_profiles(&paths)?;
                if options.json {
                    println!(
                        "{}",
                        serde_json::to_string(&profiles)
                            .map_err(|error| ZenpiError::Message(error.to_string()))?
                    );
                } else if profiles.is_empty() {
                    println!(
                        "no named profiles (legacy default configuration may still be active)"
                    );
                } else {
                    for profile in profiles {
                        println!(
                            "{}{} provider={} model={} base_url={} wire_api={} api_key={}",
                            if profile.active { "* " } else { "  " },
                            profile.name,
                            display_option(profile.provider.as_deref()),
                            display_option(profile.model.as_deref()),
                            display_option(profile.base_url.as_deref()),
                            display_option(profile.wire_api.as_deref()),
                            if profile.api_key_present {
                                "present"
                            } else {
                                "missing"
                            },
                        );
                    }
                }
                Ok(())
            }
            CliCommand::ConfigUse => {
                let paths = crate::config::ConfigPaths::discover()?;
                let profile = options
                    .command_value
                    .as_deref()
                    .ok_or_else(|| ZenpiError::arguments("config use requires a profile name"))?;
                let changed = crate::config::use_profile(&paths, profile)?;
                println!("profile={profile} changed={changed}");
                Ok(())
            }
            CliCommand::PairRevoke => {
                let paths = crate::config::ConfigPaths::discover()?;
                let Some(profile) = options.command_value.as_deref() else {
                    // The legacy root key is not owned by any profile.
                    let changed = crate::config::revoke(&paths, None)?;
                    println!("revoked={changed} local_revoked=true remote_revoked=false");
                    return Ok(());
                };
                match crate::config::profile_credential(&paths, profile)? {
                    Some(_) => {
                        let receipt = crate::config::revoke_credential(&paths, profile)?;
                        if options.json {
                            println!(
                                "{}",
                                serde_json::to_string(&receipt)
                                    .map_err(|error| ZenpiError::Message(error.to_string()))?
                            );
                        } else {
                            // The scope is what --yes confirmed, so it is shown
                            // rather than summarised as a count.
                            eprintln!(
                                "revoking credential {} affects profiles: {}",
                                receipt.credential_id,
                                receipt.profiles.join(", ")
                            );
                            println!(
                                "credential={} local_revoked={} remote_revoked={} profiles={}",
                                receipt.credential_id,
                                receipt.local_revoked,
                                receipt.remote_revoked,
                                receipt.profiles.join(",")
                            );
                        }
                        // Unbinding the profiles is deliberately not part of
                        // this command; the binding is how the operator sees
                        // why the connection stopped working.
                        Ok(())
                    }
                    None => {
                        let changed = crate::config::revoke(&paths, Some(profile))?;
                        println!("revoked={changed} local_revoked=true remote_revoked=false");
                        Ok(())
                    }
                }
            }
            CliCommand::SessionList => {
                let paths = crate::config::ConfigPaths::discover()?;
                let sessions = crate::session::list_sessions_with_fallback(
                    &paths.sessions,
                    paths.root.join("session.jsonl"),
                )?;
                if options.json {
                    println!(
                        "{}",
                        serde_json::to_string(&sessions)
                            .map_err(|error| ZenpiError::Message(error.to_string()))?
                    );
                } else if sessions.is_empty() {
                    println!("no sessions");
                } else {
                    for session in sessions {
                        print_session_summary(&session);
                    }
                }
                Ok(())
            }
            CliCommand::SessionInspect => {
                let path = options
                    .command_value
                    .as_deref()
                    .ok_or_else(|| ZenpiError::arguments("session inspect requires PATH"))?;
                let session = crate::session::inspect_session(path)?;
                if options.json {
                    println!(
                        "{}",
                        serde_json::to_string(&session)
                            .map_err(|error| ZenpiError::Message(error.to_string()))?
                    );
                } else {
                    print_session_summary(&session.summary);
                    for turn in &session.turns {
                        println!("{:?}\t{}\t{}", turn.role, turn.id, turn.content);
                    }
                }
                Ok(())
            }
            CliCommand::SessionFork => {
                let (source, destination) = command_source_destination(&options)?;
                let source = SessionStore::open(source)?;
                let fork = source.fork_to(destination)?;
                print_session_summary(&fork.summary());
                Ok(())
            }
            CliCommand::SessionExport => {
                let (source, destination) = command_source_destination(&options)?;
                SessionStore::open(source)?.export_to(destination)?;
                println!("exported={destination}");
                Ok(())
            }
            CliCommand::SessionImport => {
                let (source, destination) = command_source_destination(&options)?;
                let imported = crate::session::import_session(source, destination)?;
                print_session_summary(&imported.summary());
                Ok(())
            }
            CliCommand::SessionGc => {
                let paths = crate::config::ConfigPaths::discover()?;
                let removed = crate::session::garbage_collect_sessions(
                    &paths.sessions,
                    crate::session::GarbageCollectionPolicy {
                        retain_newest: options.retain_newest.unwrap_or_default(),
                        older_than_ms: options
                            .older_than_seconds
                            .unwrap_or_default()
                            .saturating_mul(1_000),
                    },
                    crate::session::unix_time_ms(),
                )?;
                for path in &removed {
                    println!("removed={}", path.display());
                }
                println!("removed_count={}", removed.len());
                Ok(())
            }
            CliCommand::ExtensionList => {
                let paths = crate::config::ConfigPaths::discover()?;
                let catalog = crate::extensions::ExtensionCatalog::load(&paths.extensions)
                    .map_err(|error| ZenpiError::Message(error.to_string()))?;
                if options.json {
                    println!(
                        "{}",
                        serde_json::to_string(catalog.summaries())
                            .map_err(|error| ZenpiError::Message(error.to_string()))?
                    );
                } else if catalog.summaries().is_empty() {
                    println!("no extensions");
                } else {
                    for extension in catalog.summaries() {
                        println!(
                            "{} {} disabled={} compatible={} tools={}",
                            extension.name,
                            extension.version,
                            extension.disabled,
                            extension.compatible,
                            extension.tools.join(","),
                        );
                    }
                }
                Ok(())
            }
            CliCommand::ExtensionInstall | CliCommand::ExtensionUpgrade => {
                let paths = crate::config::ConfigPaths::discover()?;
                let source =
                    PathBuf::from(options.command_value.as_deref().ok_or_else(|| {
                        ZenpiError::arguments("extension source path is required")
                    })?);
                let summary = if command == CliCommand::ExtensionInstall {
                    crate::extensions::install(&paths.extensions, &source)
                } else {
                    crate::extensions::upgrade(&paths.extensions, &source)
                }
                .map_err(|error| ZenpiError::Message(error.to_string()))?;
                println!("extension={} version={}", summary.name, summary.version);
                Ok(())
            }
            CliCommand::ExtensionRemove => {
                let paths = crate::config::ConfigPaths::discover()?;
                let name = options
                    .command_value
                    .as_deref()
                    .ok_or_else(|| ZenpiError::arguments("extension name is required"))?;
                let changed = crate::extensions::remove(&paths.extensions, name)
                    .map_err(|error| ZenpiError::Message(error.to_string()))?;
                println!("removed={changed}");
                Ok(())
            }
            CliCommand::ExtensionDisable | CliCommand::ExtensionEnable => {
                let paths = crate::config::ConfigPaths::discover()?;
                let name = options
                    .command_value
                    .as_deref()
                    .ok_or_else(|| ZenpiError::arguments("extension name is required"))?;
                let disabled = command == CliCommand::ExtensionDisable;
                let changed = crate::extensions::set_disabled(&paths.extensions, name, disabled)
                    .map_err(|error| ZenpiError::Message(error.to_string()))?;
                println!("disabled={disabled} changed={changed}");
                Ok(())
            }
        };
    }
    // A first run with no usable connection is handled before the host starts:
    // the interactive host offers login, connection selection, or exit instead
    // of building an agent that cannot serve anything.  Headless keeps its
    // fail-closed behaviour (`stable error and exit status`), and anything that
    // is merely broken still propagates as itself rather than as "not logged
    // in".
    if options.mode == RunMode::Tui {
        let paths = crate::config::ConfigPaths::discover()?;
        if let crate::tui::bootstrap::AuthGate::NeedsAuth(reason) =
            crate::tui::bootstrap::auth_gate(&paths, options.profile.as_deref())?
        {
            match crate::tui::bootstrap::run_auth_bootstrap(
                &paths,
                options.profile.as_deref(),
                &reason,
            )? {
                crate::tui::bootstrap::BootstrapOutcome::Ready => {}
                crate::tui::bootstrap::BootstrapOutcome::Exited => return Ok(()),
            }
        }
    }
    let backend = make_backend(&options)?;
    // `-s NAME|ID` resolves against the cached zenpi sessions; `--session PATH`
    // keeps its literal path semantics.
    let session_path = match options.session_ref.as_deref() {
        Some(reference) => {
            let paths = crate::config::ConfigPaths::discover()?;
            crate::session::resolve_session_reference(reference, &paths.sessions).ok_or_else(
                || {
                    ZenpiError::arguments(format!(
                        "no cached zenpi session named or identified by `{reference}`; use --session PATH to open a journal"
                    ))
                },
            )?
        }
        None => options.session.clone(),
    };
    let session = SessionStore::open(&session_path)?;
    let mut agent = Agent::new(session, backend);
    agent.project_overrides = crate::config::ConfigOverrides {
        profile: options.profile.clone(),
        backend: options.backend_explicit.then(|| options.backend.clone()),
        model: options.model.clone(),
        ..crate::config::ConfigOverrides::default()
    };
    let _ = agent.acknowledge_recovery()?;
    // Advertise the complete bounded tool set. Side effects still cannot run
    // until the local approval policy grants the individual call.
    let workspace = env::current_dir()?;
    let tools = crate::tools::ToolRegistry::with_all_builtins()
        .map_err(|error| ZenpiError::Message(format!("tool registry: {error}")))?;
    let paths = crate::config::ConfigPaths::discover()?;
    let tool_context = crate::tools::ToolContext::new(workspace)
        .map_err(|error| ZenpiError::Message(format!("tool workspace: {error}")))?;
    agent.set_tools_with_resources(
        tools,
        tool_context,
        crate::tools::SideEffectPolicy::all_builtins(),
    )?;
    let approval_mode = if options.auto {
        // ZS1-180: --auto turns every approval into an immediate allow while
        // keeping the tool policy, blueprint gates and audit events intact.
        crate::approval::ApprovalMode::Never
    } else {
        match options.mode {
            RunMode::Headless => crate::approval::ApprovalMode::Always,
            RunMode::Tui => crate::approval::ApprovalMode::ReadOnly,
        }
    };
    let _ = agent.set_approval_policy(crate::approval::ApprovalPolicy {
        mode: approval_mode,
        ..crate::approval::ApprovalPolicy::default()
    });
    agent.set_max_tool_iterations(options.max_tool_iterations);
    agent.restore_resources(default_resource_paths(&paths, &env::current_dir()?), || {
        false
    })?;
    agent.configure_extensions(&paths.extensions, || false)?;
    if let Some(model) = options.model {
        agent.set_model(Some(model))?;
    } else {
        agent.restore_model_selection()?;
    }
    match options.mode {
        RunMode::Headless => crate::headless::run_stdio_owned(agent)
            .map_err(|error| ZenpiError::Message(error.to_string())),
        RunMode::Tui => crate::tui::run_async_with_profile(agent, options.profile),
    }
}

