    pub fn claim_live_mailbox(
        &mut self,
        workspace: &str,
        digest: Option<&str>,
        now_ms: u64,
        ttl_ms: u64,
    ) -> Result<Option<crate::session::MailboxMessage>, AgentError> {
        Ok(match digest {
            Some(digest) => Some(self.live_owners.claim_message(
                &self.session,
                workspace,
                digest,
                now_ms,
                ttl_ms,
            )?),
            None => self
                .live_owners
                .claim_next(&self.session, workspace, now_ms, ttl_ms)?,
        })
    }

