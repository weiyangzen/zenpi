//! Shared agent state machine and command-line dispatch.
//!
//! The important boundary is admission: a request is either `Started`,
//! `Steered`, or `NotSubmitted(reason)`.  Rejected input never reaches the
//! backend and never writes a turn, which keeps races and side effects visible
//! to callers instead of hiding them behind booleans.

