#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "lowercase")]
pub enum TurnRole {
    System,
    User,
    Assistant,
    Tool,
}

/// One immutable conversational record.  IDs are generated by the core and
/// parent IDs preserve the active-turn relationship for steering.
#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
pub struct Turn {
    pub id: String,
    #[serde(default)]
    pub parent_id: Option<String>,
    pub role: TurnRole,
    pub content: String,
    pub created_at_ms: u64,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub metadata: Option<Value>,
}

impl Turn {
    pub fn new(id: impl Into<String>, role: TurnRole, content: impl Into<String>) -> Self {
        Self {
            id: id.into(),
            parent_id: None,
            role,
            content: content.into(),
            created_at_ms: unix_time_ms(),
            metadata: None,
        }
    }

    pub fn with_parent(
        id: impl Into<String>,
        parent_id: impl Into<String>,
        role: TurnRole,
        content: impl Into<String>,
    ) -> Self {
        let mut turn = Self::new(id, role, content);
        turn.parent_id = Some(parent_id.into());
        turn
    }

    pub fn validate(&self) -> Result<(), AgentError> {
        if self.id.trim().is_empty() {
            return Err(AgentError::InvalidTurn("turn id is empty".into()));
        }
        if self.id.len() > MAX_ID_BYTES {
            return Err(AgentError::InvalidTurn(format!(
                "turn id exceeds {MAX_ID_BYTES} bytes"
            )));
        }
        if self.id.chars().any(char::is_control) {
            return Err(AgentError::InvalidTurn(
                "turn id contains control characters".into(),
            ));
        }
        if self.parent_id.as_deref().is_some_and(|parent| {
            parent.trim().is_empty()
                || parent.len() > MAX_ID_BYTES
                || parent.chars().any(char::is_control)
        }) {
            return Err(AgentError::InvalidTurn("parent turn id is invalid".into()));
        }
        if self.content.len() > MAX_TEXT_BYTES {
            return Err(AgentError::InvalidTurn(format!(
                "turn content exceeds {MAX_TEXT_BYTES} bytes"
            )));
        }
        Ok(())
    }
}

/// Input accepted by one of the named admission paths.
#[derive(Debug, PartialEq, Eq)]
pub struct TurnInputRequest {
    pub message: String,
    pub expected_turn_id: Option<String>,
    pub mode: TurnMode,
    pub attachments: Vec<crate::backend::InputAttachment>,
}

impl TurnInputRequest {
    pub fn new(message: impl Into<String>) -> Self {
        Self {
            message: message.into(),
            expected_turn_id: None,
            mode: TurnMode::StartOrSteer,
            attachments: Vec::new(),
        }
    }

    pub fn with_mode(mut self, mode: TurnMode) -> Self {
        self.mode = mode;
        self
    }

    pub fn expecting(mut self, turn_id: impl Into<String>) -> Self {
        self.expected_turn_id = Some(turn_id.into());
        self
    }

    pub fn with_attachments(mut self, attachments: Vec<crate::backend::InputAttachment>) -> Self {
        self.attachments = attachments;
        self
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum NotSubmittedReason {
    EmptyInput,
    NotIdle,
    NoActiveTurn,
    ExpectedTurnMismatch,
    ActiveTurnNotSteerable,
}

#[derive(Debug, Clone, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case", tag = "status")]
pub enum TurnSubmission {
    Started { turn_id: String },
    Steered { turn_id: String },
    NotSubmitted { reason: NotSubmittedReason },
}

impl TurnSubmission {
    pub fn accepted(&self) -> bool {
        !matches!(self, Self::NotSubmitted { .. })
    }

    pub fn turn_id(&self) -> Option<&str> {
        match self {
            Self::Started { turn_id } | Self::Steered { turn_id } => Some(turn_id),
            Self::NotSubmitted { .. } => None,
        }
    }
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum AgentPhase {
    Idle,
    Running,
    Closed,
}

#[derive(Debug, Clone, Serialize, Deserialize, PartialEq)]
