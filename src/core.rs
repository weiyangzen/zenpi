    /// synchronous prompt.  It intentionally goes through the same typed
    /// admission path as headless mode.
    pub fn process_sync(
        &mut self,
        message: impl Into<String>,
    ) -> Result<ProcessResult, AgentError> {
        self.process(TurnInputRequest::new(message))
    }

    pub fn take_events(&mut self) -> Vec<AgentEvent> {
        std::mem::take(&mut self.events)
    }

    /// Install a bounded tool registry for subsequent provider turns. The
    /// default agent has no tools, so embedders must opt in explicitly.
    pub fn set_tools(
        &mut self,
        registry: ToolRegistry,
        context: ToolContext,
        policy: SideEffectPolicy,
    ) {
        self.tools = Some(ToolRuntime {
            registry,
            context,
            policy,
            approval: ApprovalCoordinator::new(),
            approval_policy: ApprovalPolicy::default(),
            worker_binding: None,
        });
    }

    pub fn set_attachment_workspace(&mut self, context: ToolContext) {
        if let Some(runtime) = self.tools.as_mut() {
            runtime.context = context;
        } else {
            self.tools = Some(ToolRuntime {
                registry: ToolRegistry::new(),
                context,
                policy: SideEffectPolicy::read_only(),
                approval: ApprovalCoordinator::new(),
                approval_policy: ApprovalPolicy::default(),
                worker_binding: None,
            });
        }
    }

    /// Return the host-fixed workspace used to materialize path attachments.
    /// Hosts can use this to resolve slash-command paths against the same
    /// boundary as provider requests instead of assuming the process cwd.
    pub fn attachment_workspace_root(&self) -> Option<&Path> {
        self.tools
            .as_ref()
            .map(|runtime| runtime.context.workspace_root())
    }

    /// Stage one validated attachment for the next admitted turn.  The
    /// workspace bytes are read once now to prove that the path is valid and
    /// bounded, then read and hashed again at turn admission so the provider
    /// sees the current file rather than a stale snapshot.  Bytes are never
    /// retained in the journal by this operation.
    pub fn stage_attachment(
        &mut self,
        attachment: crate::backend::InputAttachment,
    ) -> Result<(), AgentError> {
        if self.phase == AgentPhase::Closed {
            return Err(AgentError::Closed);
        }
        attachment.validate()?;
        if self.pending_attachments.len() >= crate::backend::MAX_ATTACHMENTS_PER_TURN {
            return Err(AgentError::InvalidTurn(format!(
                "pending attachments exceed {}",
                crate::backend::MAX_ATTACHMENTS_PER_TURN
            )));
        }
        // A path attachment must be checked against the host-fixed tool
        // workspace now. URL/provider-file references do not need local I/O.
        if attachment.path.is_some() {
            let _ = self
                .materialize_attachments("pending-attachment", std::slice::from_ref(&attachment))?;
        }
        self.pending_attachments.push(attachment);
        Ok(())
    }

    /// Return references waiting to be consumed by the next turn.  The slice
    /// contains no file bytes and is safe for bounded status projections.
    pub fn pending_attachments(&self) -> &[crate::backend::InputAttachment] {
        &self.pending_attachments
    }

    /// Drop staged references explicitly, for example when a host switches to
    /// another session or the user cancels an attachment workflow.
    pub fn clear_pending_attachments(&mut self) {
        self.pending_attachments.clear();
    }

    /// Configure the approval policy and return the coordinator used by a
    /// host to surface/respond to pending side-effect requests.
    pub fn set_approval_policy(&mut self, policy: ApprovalPolicy) -> Option<ApprovalCoordinator> {
        let runtime = self.tools.as_mut()?;
        runtime.approval_policy = policy;
        Some(runtime.approval.clone())
    }

    pub fn approval_coordinator(&self) -> Option<ApprovalCoordinator> {
        self.tools.as_ref().map(|runtime| runtime.approval.clone())
    }

    /// Bind subsequent calls to one lease without granting capabilities or
    /// changing interactive approval. The binding cannot change mid-turn.
    pub fn set_worker_execution_binding(
        &mut self,
        binding: Option<WorkerExecutionBinding>,
    ) -> Result<(), AgentError> {
        if self.phase != AgentPhase::Idle {
            return Err(AgentError::NotIdle);
        }
        if let Some(binding) = &binding {
            binding.validate()?;
        }
        let runtime = self.tools.as_mut().ok_or_else(|| {
            AgentError::InvalidTurn("worker binding requires a configured tool runtime".into())
        })?;
        if let Some(gate) = runtime.context.policy_evidence() {
            let Some(binding) = &binding else {
                return Err(AgentError::InvalidTurn(
                    "a worker gate requires its matching binding".into(),
                ));
            };
            validate_worker_gate_binding(binding, &gate)?;
        }
        runtime.worker_binding = binding;
        Ok(())
    }

    /// A durable dispatch without a known result is not proof of failure or
    /// success. In particular, acknowledging generic recovery never clears
    /// this gate and cannot authorize a second side effect.
    pub fn unknown_tool_outcomes(&self) -> Vec<UnknownToolOutcome> {
        let mut pending = BTreeMap::<String, UnknownToolOutcome>::new();
        for event in self.session.events() {
            let Some(operation_id) = event.get("operation_id").and_then(Value::as_str) else {
                continue;
            };
            match event.get("type").and_then(Value::as_str) {
                Some("tool_execution_started" | "tool_unknown_outcome") => {
                    if let Ok(outcome) = serde_json::from_value::<UnknownToolOutcome>(event.clone())
                    {
                        pending.insert(operation_id.to_owned(), outcome);
                    }
                }
                Some("tool_execution_finished")
                    if event.get("outcome").and_then(Value::as_str) != Some("unknown_outcome") =>
                {
                    pending.remove(operation_id);
                }
                Some("tool_recovery_decided") => {
                    pending.remove(operation_id);
                }
                _ => {}
            }
        }
        pending.into_values().collect()
    }

    /// Record an explicit host decision; `retry` permits a future user turn
    /// but never reexecutes the call here or marks an external task complete.
    pub fn resolve_tool_outcome(
        &mut self,
        operation_id: &str,
        decision: ToolRecoveryDecision,
    ) -> Result<(), AgentError> {
        if self.phase != AgentPhase::Idle {
            return Err(AgentError::NotIdle);
        }
        let pending = self
            .unknown_tool_outcomes()
            .into_iter()
            .find(|pending| pending.operation_id == operation_id)
            .ok_or_else(|| AgentError::Recovery("unknown tool operation is not pending".into()))?;
        // A crash before result persistence leaves an unmatched assistant
        // call. Supply a truthful error, never an invented successful output.
        if !self.session.turns().iter().any(|turn| {
            turn.role == TurnRole::Tool
                && turn
                    .metadata
                    .as_ref()
                    .and_then(|metadata| metadata.get("operation_id"))
                    .and_then(Value::as_str)
                    == Some(operation_id)
        }) {
            let result = tool_failure(
                &crate::tools::ToolCall {
                    id: pending.call_id.clone(),
                    name: pending.tool.clone(),
                    arguments: serde_json::json!({}),
                },
                crate::tools::ToolErrorCode::Internal,
                "unknown_outcome: prior execution has no durable result; no automatic retry",
                ToolInvocationOutcome::UnknownOutcome,
            );
            let mut turn = Turn::with_parent(
                next_id("tool"),
                &pending.turn_id,
                TurnRole::Tool,
                serde_json::to_string(&result.result)
                    .map_err(|error| AgentError::Recovery(error.to_string()))?,
            );
            turn.metadata = Some(serde_json::json!({
                "operation_id": operation_id,
                "tool_call_id": pending.call_id,
                "tool_name": pending.tool,
                "policy_digest": pending.policy_digest,
                "worker_binding": pending.worker_binding,
                "outcome": "unknown_outcome",
            }));
            self.session.append_turn(turn)?;
        }
        self.session.append_event(serde_json::json!({
            "type": "tool_recovery_decided",
            "operation_id": operation_id,
            "call_id": pending.call_id,
            "policy_digest": pending.policy_digest,
            "worker_binding": pending.worker_binding,
            "decision": decision,
            "execution_started": false,
        }))?;
        self.session
            .finish_operation(operation_id, crate::session::OperationOutcome::Interrupted)?;
        Ok(())
    }

    /// Resolve one pending tool approval and durably record the accepted host
    /// decision before the worker may enter the side-effecting handler.
    pub fn respond_to_approval(
        &self,
        response: crate::approval::ApprovalResponse,
    ) -> Result<ApprovalRequest, AgentError> {
        let Some(runtime) = self.tools.as_ref() else {
            return Err(AgentError::InvalidTurn(
                "no tool registry or approval coordinator is configured".into(),
            ));
        };
        let request = runtime.approval.reveal(&response.request_id)?;
        runtime.approval.respond(response)?;
        Ok(request)
    }

