impl TurnSubmission {
    pub fn accepted(&self) -> bool {
        !matches!(self, Self::NotSubmitted { .. })
    }

    pub fn turn_id(&self) -> Option<&str> {
        match self {
            Self::Started { turn_id } | Self::Steered { turn_id } => Some(turn_id),
            Self::NotSubmitted { .. } => None,
        }
    }
}

