pub fn parse_args<I, S>(args: I) -> Result<CliOptions, ZenpiError>
where
    I: IntoIterator<Item = S>,
    S: Into<String>,
{
    let mut options = CliOptions::default();
    let mut args = args.into_iter().map(Into::into).peekable();
    if args.peek().is_some_and(|argument| {
        matches!(
            argument.as_str(),
            "config" | "pair" | "session" | "extension"
        )
    }) {
        let group = args.next().unwrap_or_default();
        let action = args
            .next()
            .ok_or_else(|| ZenpiError::arguments(format!("{group} requires an action")))?;
        options.command = Some(match (group.as_str(), action.as_str()) {
            ("config", "import-codex") => CliCommand::ConfigImportCodex,
            ("config", "doctor") => CliCommand::ConfigDoctor,
            ("config", "list") => CliCommand::ConfigList,
            ("config", "use") => CliCommand::ConfigUse,
            ("pair", "import-codex") => CliCommand::PairImportCodex,
            ("pair", "status") => CliCommand::PairStatus,
            ("pair", "revoke") => CliCommand::PairRevoke,
            ("session", "list") => CliCommand::SessionList,
            ("session", "inspect") => CliCommand::SessionInspect,
            ("session", "fork") => CliCommand::SessionFork,
            ("session", "export") => CliCommand::SessionExport,
            ("session", "import") => CliCommand::SessionImport,
            ("session", "gc") => CliCommand::SessionGc,
            ("extension", "list") => CliCommand::ExtensionList,
            ("extension", "install") => CliCommand::ExtensionInstall,
            ("extension", "remove") => CliCommand::ExtensionRemove,
            ("extension", "disable") => CliCommand::ExtensionDisable,
            ("extension", "enable") => CliCommand::ExtensionEnable,
            ("extension", "upgrade") => CliCommand::ExtensionUpgrade,
            _ => {
                return Err(ZenpiError::arguments(format!(
                    "unknown {group} action `{action}`"
                )));
            }
        });
        while let Some(argument) = args.next() {
            match argument.as_str() {
                "--json"
                    if matches!(
                        options.command,
                        Some(
                            CliCommand::ConfigDoctor
                                | CliCommand::ConfigList
                                | CliCommand::PairStatus
                                | CliCommand::SessionList
                                | CliCommand::SessionInspect
                                | CliCommand::ExtensionList
                        )
                    ) =>
                {
                    options.json = true;
                }
                "--yes"
                    if matches!(
                        options.command,
                        Some(CliCommand::PairRevoke | CliCommand::SessionGc)
                    ) =>
                {
                    options.yes = true;
                }
                "--profile" => {
                    options.command_value = Some(
                        args.next()
                            .ok_or_else(|| ZenpiError::arguments("--profile requires a name"))?,
                    );
                }
                value
                    if matches!(options.command, Some(CliCommand::ConfigUse))
                        && options.command_value.is_none() =>
                {
                    options.command_value = Some(value.to_owned());
                }
                "--retain-newest" if matches!(options.command, Some(CliCommand::SessionGc)) => {
                    let value = args.next().ok_or_else(|| {
                        ZenpiError::arguments("--retain-newest requires a number")
                    })?;
                    options.retain_newest = Some(value.parse().map_err(|_| {
                        ZenpiError::arguments("--retain-newest must be a non-negative integer")
                    })?);
                }
                "--older-than-seconds"
                    if matches!(options.command, Some(CliCommand::SessionGc)) =>
                {
                    let value = args.next().ok_or_else(|| {
                        ZenpiError::arguments("--older-than-seconds requires a number")
                    })?;
                    options.older_than_seconds = Some(value.parse().map_err(|_| {
                        ZenpiError::arguments("--older-than-seconds must be a non-negative integer")
                    })?);
                }
                value
                    if matches!(
                        options.command,
                        Some(
                            CliCommand::SessionInspect
                                | CliCommand::SessionFork
                                | CliCommand::SessionExport
                                | CliCommand::SessionImport
                        )
                    ) && options.command_value.is_none() =>
                {
                    options.command_value = Some(value.to_owned());
                }
                value
                    if matches!(
                        options.command,
                        Some(
                            CliCommand::ExtensionInstall
                                | CliCommand::ExtensionRemove
                                | CliCommand::ExtensionDisable
                                | CliCommand::ExtensionEnable
                                | CliCommand::ExtensionUpgrade
                        )
                    ) && options.command_value.is_none() =>
                {
                    options.command_value = Some(value.to_owned());
                }
                value
                    if matches!(
                        options.command,
                        Some(
                            CliCommand::SessionFork
                                | CliCommand::SessionExport
                                | CliCommand::SessionImport
                        )
                    ) && options.command_value2.is_none() =>
                {
                    options.command_value2 = Some(value.to_owned());
                }
                _ => {
                    return Err(ZenpiError::arguments(format!(
                        "unsupported argument for {group} {action}: `{argument}`"
                    )));
                }
            }
        }
        if matches!(options.command, Some(CliCommand::ConfigUse)) && options.command_value.is_none()
        {
            return Err(ZenpiError::arguments("config use requires a profile name"));
        }
        if matches!(options.command, Some(CliCommand::PairRevoke)) && !options.yes {
            return Err(ZenpiError::arguments(
                "pair revoke requires --yes confirmation",
            ));
        }
        if matches!(options.command, Some(CliCommand::SessionInspect))
            && options.command_value.is_none()
        {
            return Err(ZenpiError::arguments("session inspect requires PATH"));
        }
        if matches!(
            options.command,
            Some(
                CliCommand::ExtensionInstall
                    | CliCommand::ExtensionRemove
                    | CliCommand::ExtensionDisable
                    | CliCommand::ExtensionEnable
                    | CliCommand::ExtensionUpgrade
            )
        ) && options.command_value.is_none()
        {
            return Err(ZenpiError::arguments(format!(
                "extension {action} requires a source path or extension name"
            )));
        }
        if matches!(
            options.command,
            Some(CliCommand::SessionFork | CliCommand::SessionExport | CliCommand::SessionImport)
        ) && (options.command_value.is_none() || options.command_value2.is_none())
        {
            return Err(ZenpiError::arguments(format!(
                "session {action} requires SOURCE and DESTINATION"
            )));
        }
        if matches!(options.command, Some(CliCommand::SessionGc))
            && (!options.yes
                || options.retain_newest.is_none()
                || options.older_than_seconds.is_none())
        {
            return Err(ZenpiError::arguments(
                "session gc requires --retain-newest N --older-than-seconds N --yes",
            ));
        }
        return Ok(options);
    }
    while let Some(argument) = args.next() {
        let (flag, inline) = argument
            .split_once('=')
            .map_or((argument.as_str(), None), |(flag, value)| {
                (flag, Some(value))
            });
        match flag {
            "--help" | "-h" => options.help = true,
            "--headless" => {
                if inline.is_some() {
                    return Err(ZenpiError::arguments("--headless does not take a value"));
                }
                options.mode = RunMode::Headless;
            }
            "--tui" => {
                if inline.is_some() {
                    return Err(ZenpiError::arguments("--tui does not take a value"));
                }
                options.mode = RunMode::Tui;
            }
            "--mode" => {
                let value = inline
                    .map(str::to_owned)
                    .or_else(|| args.next())
                    .ok_or_else(|| ZenpiError::arguments("--mode requires tui or headless"))?;
                options.mode = match value.as_str() {
                    "tui" => RunMode::Tui,
                    "headless" => RunMode::Headless,
                    _ => return Err(ZenpiError::arguments("--mode must be tui or headless")),
                };
            }
            "--session" => {
                let value = inline
                    .map(str::to_owned)
                    .or_else(|| args.next())
                    .ok_or_else(|| ZenpiError::arguments("--session requires a path"))?;
                if value.trim().is_empty() {
                    return Err(ZenpiError::arguments("--session path is empty"));
                }
                options.session = PathBuf::from(value);
            }
            "--backend" => {
                options.backend = inline
                    .map(str::to_owned)
                    .or_else(|| args.next())
                    .ok_or_else(|| ZenpiError::arguments("--backend requires echo or openai"))?;
                options.backend_explicit = true;
                if options.backend.trim().is_empty()
                    || options.backend.chars().any(char::is_control)
                {
                    return Err(ZenpiError::arguments("--backend name is invalid"));
                }
            }
            "--model" => {
                let model = inline
                    .map(str::to_owned)
                    .or_else(|| args.next())
                    .ok_or_else(|| ZenpiError::arguments("--model requires a name"))?;
                if model.trim().is_empty()
                    || model.len() > 256
                    || model.chars().any(char::is_control)
                {
                    return Err(ZenpiError::arguments(
                        "--model must be non-empty and at most 256 bytes",
                    ));
                }
                options.model = Some(model);
            }
            other if other.starts_with('-') => {
                return Err(ZenpiError::arguments(format!("unknown option `{other}`")));
            }
            other => {
                return Err(ZenpiError::arguments(format!(
                    "unexpected argument `{other}`"
                )));
            }
        }
    }
    Ok(options)
}

fn make_backend(options: &CliOptions) -> Result<Box<dyn Backend>, ZenpiError> {
    match options.backend.as_str() {
        "echo" if options.backend_explicit && cfg!(feature = "dev-fixtures") => {
            Ok(Box::new(EchoBackend))
        }
        "echo" => Err(ZenpiError::arguments(
            "echo is a test fixture; rebuild with --features dev-fixtures and pass --backend echo",
        )),
        "openai" => {
            let effective = crate::config::resolve_default(&crate::config::ConfigOverrides {
                backend: options.backend_explicit.then(|| options.backend.clone()),
                model: options.model.clone(),
                ..crate::config::ConfigOverrides::default()
            })?;
            let base_url = effective.base_url.ok_or_else(|| {
                ZenpiError::arguments(
                    "no provider URL configured; run `zenpi config import-codex` or set ZENPI_BASE_URL",
                )
            })?;
            let api_key = if effective.requires_openai_auth {
                Some(effective.api_key.ok_or_else(|| {
                    ZenpiError::arguments(
                        "no provider API key configured; run `zenpi config import-codex` or set ZENPI_API_KEY",
                    )
                })?)
            } else {
                effective.api_key
            };
            let model = effective.model.ok_or_else(|| {
                ZenpiError::arguments(
                    "no provider model configured; run `zenpi config import-codex` or set ZENPI_MODEL",
                )
            })?;
            let wire_api = effective
                .wire_api
                .as_deref()
                .unwrap_or("responses")
                .parse::<OpenAiWireApi>()?;
            let backend = OpenAiCompatibleBackend::from_values_with_settings_and_timeout(
                base_url,
                api_key,
                model,
                wire_api,
                effective.model_reasoning_effort,
                effective.model_verbosity,
                std::time::Duration::from_secs(effective.timeout_seconds.unwrap_or(120)),
            )?
            .with_max_retries(effective.max_retries.unwrap_or(2))?;
            Ok(Box::new(backend))
        }
        other => Err(ZenpiError::arguments(format!(
            "unknown backend `{other}` (expected echo or openai)"
        ))),
    }
}

fn print_help() {
    println!("zenpi [--mode tui|headless] [--session PATH] [--backend openai] [--model NAME]");
    println!("zenpi config import-codex [--profile NAME]");
    println!("zenpi config doctor [--profile NAME] [--json]");
    println!("zenpi config list [--json] | config use NAME");
    println!("zenpi pair import-codex|status|revoke --yes [--profile NAME]");
    println!("zenpi session list [--json] | inspect PATH [--json]");
    println!("zenpi session fork|export|import SOURCE DESTINATION");
    println!("zenpi session gc --retain-newest N --older-than-seconds N --yes");
    println!("zenpi extension list [--json] | install|upgrade PATH");
    println!("zenpi extension disable|enable|remove NAME");
    println!(
        "default provider: ~/.zenpi (or read-only ~/.codex fallback); echo exists only in dev-fixtures builds"
    );
}

/// Binary entry point shared with tests and embedders.
pub fn run() -> Result<(), ZenpiError> {
    let options = parse_args(env::args().skip(1))?;
    if options.help {
        print_help();
        return Ok(());
    }
    if let Some(command) = options.command {
        return match command {
            CliCommand::ConfigImportCodex | CliCommand::PairImportCodex => {
                let summary = match options.command_value.as_deref() {
                    Some(profile) => crate::config::import_codex_profile(profile)?,
                    None => crate::config::import_codex()?,
                };
                println!("{}", summary.display());
                Ok(())
            }
            CliCommand::ConfigDoctor | CliCommand::PairStatus => {
                let paths = crate::config::ConfigPaths::discover()?;
                let report =
                    crate::config::status_for_profile(&paths, options.command_value.as_deref())?;
                if options.json {
                    println!(
                        "{}",
                        serde_json::to_string(&report)
                            .map_err(|error| ZenpiError::Message(error.to_string()))?
                    );
                } else {
                    print_config_status(&report);
                }
                Ok(())
            }
            CliCommand::ConfigList => {
                let paths = crate::config::ConfigPaths::discover()?;
                let profiles = crate::config::list_profiles(&paths)?;
                if options.json {
                    println!(
                        "{}",
                        serde_json::to_string(&profiles)
                            .map_err(|error| ZenpiError::Message(error.to_string()))?
                    );
                } else if profiles.is_empty() {
                    println!(
                        "no named profiles (legacy default configuration may still be active)"
                    );
                } else {
                    for profile in profiles {
                        println!(
                            "{}{} provider={} model={} base_url={} wire_api={} api_key={}",
                            if profile.active { "* " } else { "  " },
                            profile.name,
                            display_option(profile.provider.as_deref()),
                            display_option(profile.model.as_deref()),
                            display_option(profile.base_url.as_deref()),
                            display_option(profile.wire_api.as_deref()),
                            if profile.api_key_present {
                                "present"
                            } else {
                                "missing"
                            },
                        );
                    }
                }
                Ok(())
            }
            CliCommand::ConfigUse => {
                let paths = crate::config::ConfigPaths::discover()?;
                let profile = options
                    .command_value
                    .as_deref()
                    .ok_or_else(|| ZenpiError::arguments("config use requires a profile name"))?;
                let changed = crate::config::use_profile(&paths, profile)?;
                println!("profile={profile} changed={changed}");
                Ok(())
            }
            CliCommand::PairRevoke => {
                let paths = crate::config::ConfigPaths::discover()?;
                let changed = crate::config::revoke(&paths, options.command_value.as_deref())?;
                println!("revoked={changed}");
                Ok(())
            }
            CliCommand::SessionList => {
                let paths = crate::config::ConfigPaths::discover()?;
                let sessions = crate::session::list_sessions(&paths.sessions)?;
                if options.json {
                    println!(
                        "{}",
                        serde_json::to_string(&sessions)
                            .map_err(|error| ZenpiError::Message(error.to_string()))?
                    );
                } else if sessions.is_empty() {
                    println!("no sessions");
                } else {
                    for session in sessions {
                        print_session_summary(&session);
                    }
                }
                Ok(())
            }
            CliCommand::SessionInspect => {
                let path = options
                    .command_value
                    .as_deref()
                    .ok_or_else(|| ZenpiError::arguments("session inspect requires PATH"))?;
                let session = crate::session::inspect_session(path)?;
                if options.json {
                    println!(
                        "{}",
                        serde_json::to_string(&session)
                            .map_err(|error| ZenpiError::Message(error.to_string()))?
                    );
                } else {
                    print_session_summary(&session.summary);
                    for turn in &session.turns {
                        println!("{:?}\t{}\t{}", turn.role, turn.id, turn.content);
                    }
                }
                Ok(())
            }
            CliCommand::SessionFork => {
                let (source, destination) = command_source_destination(&options)?;
                let source = SessionStore::open(source)?;
                let fork = source.fork_to(destination)?;
                print_session_summary(&fork.summary());
                Ok(())
            }
            CliCommand::SessionExport => {
                let (source, destination) = command_source_destination(&options)?;
                SessionStore::open(source)?.export_to(destination)?;
                println!("exported={destination}");
                Ok(())
            }
            CliCommand::SessionImport => {
                let (source, destination) = command_source_destination(&options)?;
                let imported = crate::session::import_session(source, destination)?;
                print_session_summary(&imported.summary());
                Ok(())
            }
            CliCommand::SessionGc => {
                let paths = crate::config::ConfigPaths::discover()?;
                let removed = crate::session::garbage_collect_sessions(
                    &paths.sessions,
                    crate::session::GarbageCollectionPolicy {
                        retain_newest: options.retain_newest.unwrap_or_default(),
                        older_than_ms: options
                            .older_than_seconds
                            .unwrap_or_default()
                            .saturating_mul(1_000),
                    },
                    crate::session::unix_time_ms(),
                )?;
                for path in &removed {
                    println!("removed={}", path.display());
                }
                println!("removed_count={}", removed.len());
                Ok(())
            }
            CliCommand::ExtensionList => {
                let paths = crate::config::ConfigPaths::discover()?;
                let catalog = crate::extensions::ExtensionCatalog::load(&paths.extensions)
                    .map_err(|error| ZenpiError::Message(error.to_string()))?;
                if options.json {
                    println!(
                        "{}",
                        serde_json::to_string(catalog.summaries())
                            .map_err(|error| ZenpiError::Message(error.to_string()))?
                    );
                } else if catalog.summaries().is_empty() {
                    println!("no extensions");
                } else {
                    for extension in catalog.summaries() {
                        println!(
                            "{} {} disabled={} compatible={} tools={}",
                            extension.name,
                            extension.version,
                            extension.disabled,
                            extension.compatible,
                            extension.tools.join(","),
                        );
                    }
                }
                Ok(())
            }
            CliCommand::ExtensionInstall | CliCommand::ExtensionUpgrade => {
                let paths = crate::config::ConfigPaths::discover()?;
                let source =
                    PathBuf::from(options.command_value.as_deref().ok_or_else(|| {
                        ZenpiError::arguments("extension source path is required")
                    })?);
                let summary = if command == CliCommand::ExtensionInstall {
                    crate::extensions::install(&paths.extensions, &source)
                } else {
                    crate::extensions::upgrade(&paths.extensions, &source)
                }
                .map_err(|error| ZenpiError::Message(error.to_string()))?;
                println!("extension={} version={}", summary.name, summary.version);
                Ok(())
            }
            CliCommand::ExtensionRemove => {
                let paths = crate::config::ConfigPaths::discover()?;
                let name = options
                    .command_value
                    .as_deref()
                    .ok_or_else(|| ZenpiError::arguments("extension name is required"))?;
                let changed = crate::extensions::remove(&paths.extensions, name)
                    .map_err(|error| ZenpiError::Message(error.to_string()))?;
                println!("removed={changed}");
                Ok(())
            }
            CliCommand::ExtensionDisable | CliCommand::ExtensionEnable => {
                let paths = crate::config::ConfigPaths::discover()?;
                let name = options
                    .command_value
                    .as_deref()
                    .ok_or_else(|| ZenpiError::arguments("extension name is required"))?;
                let disabled = command == CliCommand::ExtensionDisable;
                let changed = crate::extensions::set_disabled(&paths.extensions, name, disabled)
                    .map_err(|error| ZenpiError::Message(error.to_string()))?;
                println!("disabled={disabled} changed={changed}");
                Ok(())
            }
        };
    }
    let backend = make_backend(&options)?;
    let session = SessionStore::open(&options.session)?;
    let mut agent = Agent::new(session, backend);
    let _ = agent.acknowledge_recovery()?;
    // Advertise the complete bounded tool set. Side effects still cannot run
    // until the local approval policy grants the individual call.
    let workspace = env::current_dir()?;
    let mut tools = crate::tools::ToolRegistry::with_all_builtins()
        .map_err(|error| ZenpiError::Message(format!("tool registry: {error}")))?;
    let paths = crate::config::ConfigPaths::discover()?;
    let extensions = crate::extensions::ExtensionCatalog::load(&paths.extensions)
        .map_err(|error| ZenpiError::Message(format!("extension loading: {error}")))?;
    extensions
        .register_tools(&mut tools)
        .map_err(|error| ZenpiError::Message(format!("extension tools: {error}")))?;
    let tool_context = crate::tools::ToolContext::new(workspace)
        .map_err(|error| ZenpiError::Message(format!("tool workspace: {error}")))?;
    agent.set_tools(
        tools,
        tool_context,
        crate::tools::SideEffectPolicy::all_builtins(),
    );
    let approval_mode = match options.mode {
        RunMode::Headless => crate::approval::ApprovalMode::Always,
        RunMode::Tui => crate::approval::ApprovalMode::ReadOnly,
    };
    let _ = agent.set_approval_policy(crate::approval::ApprovalPolicy {
        mode: approval_mode,
        ..crate::approval::ApprovalPolicy::default()
    });
    let project_skills = env::current_dir()?.join(".zenpi").join("skills");
    let skills = crate::skills::SkillSet::load(&paths.skills, &project_skills)
        .map_err(|error| ZenpiError::Message(format!("skill loading: {error}")))?;
    agent.set_skills(skills);
    if let Some(model) = options.model {
        agent.set_model(Some(model))?;
    }
    match options.mode {
        RunMode::Headless => crate::headless::run_stdio_owned(agent)
            .map_err(|error| ZenpiError::Message(error.to_string())),
        RunMode::Tui => crate::tui::run_async(agent),
    }
}

fn display_option(value: Option<&str>) -> &str {
    value.unwrap_or("<not configured>")
}

fn command_source_destination(options: &CliOptions) -> Result<(&str, &str), ZenpiError> {
    let source = options
        .command_value
        .as_deref()
        .ok_or_else(|| ZenpiError::arguments("session command requires SOURCE"))?;
    let destination = options
        .command_value2
        .as_deref()
        .ok_or_else(|| ZenpiError::arguments("session command requires DESTINATION"))?;
    Ok((source, destination))
}

fn print_session_summary(summary: &crate::session::SessionSummary) {
    println!(
        "session={} path={} turns={} events={} handoffs={} warnings={} next_seq={}",
        summary.session_id,
        summary.path,
        summary.turn_count,
        summary.event_count,
        summary.handoff_count,
        summary.recovery_warnings,
        summary.next_seq,
    );
}

fn print_config_status(report: &crate::config::ConfigStatus) {
    println!("profile={}", display_option(report.profile.as_deref()));
    println!(
        "ready={}",
        (!report.requires_openai_auth || report.api_key_present)
            && report.base_url.is_some()
            && report.model.is_some()
    );
    println!("backend={}", report.backend);
    println!("provider={}", display_option(report.provider.as_deref()));
    println!("base_url={}", display_option(report.base_url.as_deref()));
    println!("wire_api={}", display_option(report.wire_api.as_deref()));
    println!("model={}", display_option(report.model.as_deref()));
    println!("requires_openai_auth={}", report.requires_openai_auth);
    println!("supports_websockets={}", report.supports_websockets);
    println!(
        "api_key={}",
        if report.api_key_present {
            "present"
        } else {
            "missing"
        }
    );
}
