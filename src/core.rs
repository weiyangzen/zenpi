fn unix_time_ms() -> u64 {
    SystemTime::now()
        .duration_since(UNIX_EPOCH)
        .unwrap_or_default()
        .as_millis()
        .min(u128::from(u64::MAX)) as u64
}

fn validate_worker_gate_binding(
    binding: &WorkerExecutionBinding,
    gate: &crate::tools::PolicyEvidence,
) -> Result<(), AgentError> {
    binding.validate()?;
    if binding.policy_digest != gate.policy_digest
        || binding.blueprint_sha256 != gate.blueprint_digest
        || binding.item_id != gate.item_id
        || binding.lease_id != gate.lease_id
        || binding.expires_at_ms != gate.expires_at_ms
        || !gate.prohibition_gate_enforced
    {
        return Err(AgentError::InvalidTurn(
            "worker binding does not match the compiled prohibition gate".into(),
        ));
    }
    Ok(())
}

fn approval_request_id(
    session_id: &str,
    turn_id: &str,
    call_id: &str,
    policy_digest: &str,
) -> String {
    use sha2::{Digest, Sha256};
    let encoded = serde_json::to_vec(&(session_id, turn_id, call_id, policy_digest))
        .expect("string tuple serializes");
    format!("approval-{:x}", Sha256::digest(encoded))
}

fn provider_idempotency_key(turn_id: &str) -> String {
    use sha2::{Digest, Sha256};
    format!("provider-{:x}", Sha256::digest(turn_id.as_bytes()))
}

fn next_id(prefix: &str) -> String {
    format!(
        "{prefix}-{}-{}",
        unix_time_ms(),
        NEXT_ID.fetch_add(1, Ordering::Relaxed)
    )
}

fn attachment_journal_metadata(attachments: &[crate::backend::RequestAttachment]) -> Vec<Value> {
    attachments
        .iter()
        .map(|attachment| {
            serde_json::json!({
                "kind": attachment.input.kind,
                "mime_type": attachment.input.mime_type,
                "path": attachment.input.path,
                "url": attachment.input.url,
                "file_id": attachment.input.file_id,
                "size_bytes": attachment.size_bytes,
                "sha256": attachment.sha256,
            })
        })
        .collect()
}

