import { readFileSync, mkdirSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { gunzipSync } from 'node:zlib';
import { join } from 'node:path';
if (process.platform !== 'darwin' || process.arch !== 'arm64') throw Error('Frozen fd requires Darwin arm64');
const receipt=JSON.parse(readFileSync(new URL('./fd-provision.json',import.meta.url),'utf8'));
const raw=gunzipSync(readFileSync(new URL('./runtime/native/fd-darwin-arm64.gz',import.meta.url)));
const hash=createHash('sha256').update(raw).digest('hex');
if(hash!==receipt.sha256||raw.length!==receipt.bytes)throw Error('fd bytes mismatch');
const agent=process.env.PI_CODING_AGENT_DIR;if(!agent)throw Error('Set isolated PI_CODING_AGENT_DIR');
mkdirSync(join(agent,'bin'),{recursive:true});writeFileSync(join(agent,'bin','fd'),raw,{mode:0o755,flag:'wx'});
console.log(JSON.stringify({path:join(agent,'bin','fd'),bytes:raw.length,sha256:hash}));
